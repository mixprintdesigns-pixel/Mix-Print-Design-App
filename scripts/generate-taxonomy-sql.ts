// Writes the data part of migration 20261102090000_shared_category_tree from prisma/taxonomy.
// Run: npx tsx scripts/generate-taxonomy-sql.ts > /tmp/data.sql
// The migration is idempotent and never overwrites a category already edited in the new system
// (content IS NOT NULL), never deletes categories and never deletes products.
import { TAXONOMY, type TaxonomyNode } from "../prisma/taxonomy";

const q = (s: string | undefined | null) => (s == null ? "NULL" : `'${s.replace(/'/g, "''")}'`);

const lines: string[] = [];
const vars: string[] = [];
let n = 0;

function emit(node: TaxonomyNode, parentVar: string, sort: number, path: string): string {
  const v = `c${++n}`;
  vars.push(v);
  lines.push(
    `  ${v} := pg_temp.mp_ensure_cat(${parentVar}, ${q(node.slug)}, ${q(node.name)}, ${q(node.short)}, ${q(node.content)}, ${q(node.priceUnit)}, ${sort}); -- ${path}`,
  );
  (node.children ?? []).forEach((child, i) => emit(child, v, i, `${path}/${child.slug}`));
  return v;
}

// 1. Main services first, so old categories can be moved under them before the rest is created.
const mains = TAXONOMY.map((m, i) => {
  const v = `m_${m.slug.replace(/-/g, "_")}`;
  vars.push(v);
  lines.push(`  ${v} := pg_temp.mp_ensure_cat(NULL, ${q(m.slug)}, ${q(m.name)}, ${q(m.short)}, ${q(m.content)}, ${q(m.priceUnit)}, ${i});`);
  return { node: m, v };
});

// 2. Move the original demo categories into the tree (keeps their products and ids).
const moves: [oldSlug: string, main: string, newSlug: string][] = [
  ["business-cards", "m_offset_printing", "business-cards"],
  ["marketing", "m_offset_printing", "flyers-leaflets"],
  ["stickers-labels", "m_offset_printing", "stickers-labels"],
  ["packaging", "m_offset_printing", "packaging-boxes"],
  ["stationery", "m_offset_printing", "letterheads"],
  ["large-format", "m_digital_printing", "standees-roll-up-banners"],
];
lines.push("", "  -- Move the original product categories under their main service");
for (const [oldSlug, main, newSlug] of moves) {
  lines.push(
    `  UPDATE "Category" SET "parentId" = ${main}, slug = ${q(newSlug)} WHERE "parentId" IS NULL AND slug = ${q(oldSlug)}` +
      ` AND NOT EXISTS (SELECT 1 FROM "Category" WHERE "parentId" = ${main} AND slug = ${q(newSlug)});`,
  );
}

// 3. Everything below the main services.
lines.push("", "  -- Categories and sub-categories");
for (const { node, v } of mains) (node.children ?? []).forEach((c, i) => emit(c, v, i, `${node.slug}/${c.slug}`));

const sql = `
-- ─── Data: the shared category tree (generated by scripts/generate-taxonomy-sql.ts) ───

-- Finds a category by parent + slug or creates it. Text is filled in only for categories
-- not yet edited in the new system (content IS NULL), so admin edits are never overwritten.
CREATE OR REPLACE FUNCTION pg_temp.mp_ensure_cat(p_parent text, p_slug text, p_name text, p_short text, p_content text, p_unit text, p_sort int)
RETURNS text LANGUAGE plpgsql AS $fn$
DECLARE v_id text;
BEGIN
  SELECT id INTO v_id FROM "Category" WHERE slug = p_slug AND "parentId" IS NOT DISTINCT FROM p_parent LIMIT 1;
  IF v_id IS NULL THEN
    v_id := 'cat_' || substr(md5(coalesce(p_parent, '') || '/' || p_slug), 1, 20);
    INSERT INTO "Category" (id, name, slug, description, content, "priceUnit", "sortOrder", "parentId", "isVisible", "createdAt", "updatedAt")
    VALUES (v_id, p_name, p_slug, p_short, p_content, p_unit, p_sort, p_parent, true, now(), now());
  ELSE
    UPDATE "Category"
    SET name = p_name, description = p_short, content = p_content, "priceUnit" = coalesce("priceUnit", p_unit), "sortOrder" = p_sort, "updatedAt" = now()
    WHERE id = v_id AND content IS NULL;
  END IF;
  RETURN v_id;
END $fn$;

DO $mig$
DECLARE
  ${vars.map((v) => `${v} text;`).join(" ")}
BEGIN
${lines.join("\n")}
END $mig$;
`;
process.stdout.write(sql);
